"""
apply_lipsync.py — Blender background script for lip-sync rendering.

Runs INSIDE Blender.  Reads a lipsync JSON, renders each frame with the
correct mouth-shape applied to the mouth mesh object.

Usage:
    blender --background <blend_file> --python apply_lipsync.py \\
        -- <lipsync_json> <char_name> <output_dir>

Arguments after '--':
    lipsync_json : path to lipsync JSON generated by LipsyncGenerator
    char_name    : 'Aarav' or 'Aanya'
    output_dir   : directory to write frame_NNNN.png files

Prints 'LIPSYNC_RENDER_OK' on success.
"""

import sys
import os
import json
from pathlib import Path

# ---------------------------------------------------------------------------
# Parse arguments
# ---------------------------------------------------------------------------
if "--" not in sys.argv:
    print("ERROR: missing arguments after '--'")
    sys.exit(1)

args = sys.argv[sys.argv.index("--") + 1:]
if len(args) < 3:
    print("ERROR: need <lipsync_json> <char_name> <output_dir>")
    sys.exit(1)

lipsync_json_path = args[0]
char_name = args[1]   # 'Aarav' or 'Aanya'
output_dir = args[2]

sys.path.insert(0, str(Path(__file__).resolve().parent))
import bpy
from facial_preview import mouth_surface, setup_preview, viseme_pose
from studio.dialogue.expression_library import apply_expression, restore_expression
from studio.dialogue.mouth_shapes import BLINK_DURATION_FRAMES

# ---------------------------------------------------------------------------
# Load lipsync data
# ---------------------------------------------------------------------------
if not os.path.isfile(lipsync_json_path):
    print(f"ERROR: lipsync JSON not found: {lipsync_json_path}")
    sys.exit(1)

with open(lipsync_json_path, "r", encoding="utf-8") as fh:
    lipsync = json.load(fh)

fps = int(lipsync.get("fps", 24))
total_frames = int(lipsync.get("total_frames", 24))
frames_data = {int(k): v for k, v in lipsync.get("frames", {}).items()}
blink_frames_set = set(int(b) for b in lipsync.get("blink_frames", []))

# ---------------------------------------------------------------------------
# Mouth object
# ---------------------------------------------------------------------------
mouth_obj_name = f"{char_name}_Mouth"
mouth_obj = bpy.data.objects.get(mouth_obj_name)
if mouth_obj is None:
    print(f"ERROR: mouth object '{mouth_obj_name}' not found in scene")
    sys.exit(1)

# Set up the scene before recording the expression's eye scales.
scene = setup_preview(char_name)
scene.render.fps = fps
emotion = lipsync.get("emotion", "neutral")
saved_expression = apply_expression(char_name, emotion)

# Eye objects for blink
# ---------------------------------------------------------------------------
eye_scales = {
    obj: obj.scale.z
    for suffix in ("Eye_L", "Eye_R", "Iris_L", "Iris_R")
    if (obj := bpy.data.objects.get(f"{char_name}_{suffix}")) is not None
}

# Output directory
os.makedirs(output_dir, exist_ok=True)

# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

def apply_blink(fraction: float) -> None:
    """fraction 0.0 = open, 1.0 = fully closed."""
    for eye, rest_z_scale in eye_scales.items():
        eye.scale.z = rest_z_scale * max(0.05, 1.0 - fraction)

# ---------------------------------------------------------------------------
# Render loop
# ---------------------------------------------------------------------------
rendered_count = 0
for frame_num in range(1, total_frames + 1):
    scene.frame_set(frame_num)
    viseme = frames_data.get(frame_num, "REST")

    # Blink handling: closed on blink_frame, gradually re-open over duration
    if frame_num in blink_frames_set:
        apply_blink(1.0)  # fully closed
    elif any(
        (frame_num > bf) and (frame_num <= bf + BLINK_DURATION_FRAMES)
        for bf in blink_frames_set
    ):
        # Find relevant blink frame
        for bf in sorted(blink_frames_set):
            if bf < frame_num <= bf + BLINK_DURATION_FRAMES:
                progress = (frame_num - bf) / BLINK_DURATION_FRAMES
                apply_blink(1.0 - progress)
                break
    else:
        apply_blink(0.0)

    # Render
    output_path = os.path.join(output_dir, f"frame_{frame_num:04d}.png")
    scene.render.filepath = output_path
    profile = emotion if viseme == "REST" else viseme
    with viseme_pose(mouth_obj, viseme), mouth_surface(char_name, profile):
        bpy.ops.render.render(write_still=True)
    rendered_count += 1

apply_blink(0.0)
restore_expression(saved_expression)

print(f"\n=== LIPSYNC RENDER SUMMARY ===")
print(f"Character  : {char_name}")
print(f"Total frames: {total_frames}")
print(f"Rendered   : {rendered_count}")
print(f"Output dir : {output_dir}")
print("LIPSYNC_RENDER_OK")
sys.exit(0)
